#!/usr/bin/env python3
"""
Builds src/world.h, the overworld of DUNGEON, from world/world.txt.

It checks the map before writing it: sizes, characters, that every place
can be reached from the start and that every entrance and sign can be
used from the tile below it.

Usage:  python3 world/make_world.py
"""
import os
import sys
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'world.txt')
OUTPUT = os.path.join(HERE, '..', 'src', 'world.h')
SW, SH, NX, NY = 15, 13, 8, 6
CHARS = set('.,:sT#o%~=*+!@12345abcd')
WALK = set('.,:s=@12345abcd')          # the hero can step on these
REGIONS = 'GFMCHLDBPRS'
FONT = set('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:!-.+*/\' ')


def fail(msg):
    raise SystemExit('world.txt: ' + msg)


def main():
    section, rows, screens, signs = None, [], [], []
    for line in open(SOURCE):
        line = line.rstrip('\n')
        if line.startswith('#') or not line.strip():
            continue
        if line.startswith('['):
            section = line.strip('[]')
            continue
        if section == 'map':
            rows.append(line)
        elif section == 'screens':
            screens.append(line.split())
        elif section == 'signs':
            sx, sy, text = line.split(None, 2)
            signs.append((int(sx), int(sy), text))

    W, H = SW * NX, SH * NY
    if len(rows) != H or any(len(r) != W for r in rows):
        fail('the map must be %d lines of %d characters' % (H, W))
    for y, r in enumerate(rows):
        bad = set(r) - CHARS
        if bad:
            fail('line %d: unknown characters %s' % (y + 1, ''.join(sorted(bad))))
    if len(screens) != NY or any(len(s) != 2 or len(s[0]) != NX or len(s[1]) != NX
                                 for s in screens):
        fail('[screens] needs %d lines "regions dangers" of %d characters' % (NY, NX))
    for reg, lev in screens:
        if set(reg) - set(REGIONS) or set(lev) - set('0123'):
            fail('[screens]: regions are %s, dangers 0 - 3' % REGIONS)
    starts = [(x, y) for y in range(H) for x in range(W) if rows[y][x] == 's']
    if len(starts) != 1:
        fail('there must be exactly one start (s)')
    for sx, sy, text in signs:
        if len(text) > 18 or set(text) - FONT:
            fail('sign "%s": up to 18 characters A-Z 0-9 : ! - . + * / \'' % text)
        if not any(rows[sy * SH + y][sx * SW + x] == '!' for y in range(SH) for x in range(SW)):
            fail('screen %d %d has a sign text but no sign' % (sx, sy))
    for ch in '12345abcd':
        if sum(r.count(ch) for r in rows) != 1:
            fail('"%s" must appear exactly once' % ch)

    # everything the hero can walk on must be reachable from the start
    seen = {starts[0]}
    q = deque(seen)
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and \
                    rows[ny][nx] in WALK | {'*'}:
                seen.add((nx, ny))
                q.append((nx, ny))
    for y in range(H):
        for x in range(W):
            c = rows[y][x]
            if c in WALK and (x, y) not in seen:
                fail('(%d, %d) in screen %d %d cannot be reached' % (x, y, x // SW, y // SH))
            if c in '12345abcd!' and (y + 1 >= H or (x, y + 1) not in seen):
                fail('"%s" at (%d, %d) needs a reachable tile below it' % (c, x, y))

    out = ['/**',
           '    Overworld of DUNGEON: %d x %d screens of %d x %d tiles.' % (NX, NY, SW, SH),
           '    Generated by world/make_world.py from world/world.txt - do not edit.',
           '*/', '',
           '#define WORLD_SX %d' % NX, '#define WORLD_SY %d' % NY, '',
           'static const char world[%d][%d] = {' % (H, W)]
    out += ['    "%s",' % r for r in rows]
    out += ['};', '', '// region and danger of every screen',
            'static const char screen_region[%d][%d] = {' % (NY, NX)]
    out += ['    "%s",' % s[0] for s in screens]
    out += ['};', 'static const char screen_danger[%d][%d] = {' % (NY, NX)]
    out += ['    "%s",' % s[1] for s in screens]
    out += ['};', '', 'struct sign {', '    uint8_t screen;', '    const char *text;', '};',
            'static const struct sign signs[] = {']
    out += ['    {%d, "%s"},' % (sy * NX + sx, t) for sx, sy, t in signs]
    out += ['};', '#define SIGNS (sizeof(signs) / sizeof(signs[0]))', '']
    with open(OUTPUT, 'w') as f:
        f.write('\n'.join(out))
    print('world: %d x %d tiles, %d walkable, %d signs -> %s' %
          (W, H, len(seen), len(signs), os.path.relpath(OUTPUT)))


if __name__ == '__main__':
    main()
