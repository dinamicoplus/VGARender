#!/usr/bin/env python3
"""
Builds src/roms.h, the ROM table of the CHIP-8 interpreter, from the files
in chip8/roms/:

  - name.asm   assembled with asm.py
  - name.ch8   used as is (for example a ROM you downloaded)

Each ROM can declare its menu entry in comment lines, inside the .asm or in
a name.txt file next to the .ch8:

    ; name: DODGE           menu name (A-Z, 0-9, - : . / and spaces)
    ; keys: 4 6 - 5 F       CHIP-8 key for knob left, knob right, S1, S2
                            and S1 + S2 together (hex digit, or - for
                            none; the fifth one is optional)
    ; quirks: vip           vip (COSMAC VIP, default), chip48 or schip
    ; speed: 12             instructions per frame (60 frames per second)

Usage:  python3 make_roms.py
"""
import os
import re
import sys

from asm import AsmError, assemble

HERE = os.path.dirname(os.path.abspath(__file__))
ROM_DIR = os.path.join(HERE, 'roms')
OUTPUT = os.path.join(HERE, '..', 'src', 'roms.h')
MAX_SIZE = 4096 - 0x200
NAME_CHARS = set('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-:>+./ ')


def metadata(text, default_name):
    meta = {'name': default_name, 'keys': '- - - - -', 'quirks': 'vip', 'speed': '12'}
    for m in re.finditer(r'^\s*;?\s*(name|keys|quirks|speed)\s*:\s*(.+?)\s*(\(.*)?$',
                         text, re.MULTILINE):
        meta[m.group(1)] = m.group(2)
    return meta


def c_keys(spec, rom):
    keys = spec.split()
    if len(keys) == 4:
        keys.append('-')
    if len(keys) != 5:
        raise SystemExit(f'{rom}: "keys" needs 4 or 5 entries '
                         '(knob left, knob right, S1, S2, S1 + S2)')
    out = []
    for k in keys:
        if k == '-':
            out.append('KEY_NONE')
        elif re.fullmatch(r'[0-9a-fA-F]', k):
            out.append('0x' + k.upper())
        else:
            raise SystemExit(f'{rom}: bad key "{k}"')
    return ', '.join(out)


def main():
    entries = []
    for file in sorted(os.listdir(ROM_DIR)):
        base, ext = os.path.splitext(file)
        path = os.path.join(ROM_DIR, file)
        if ext == '.asm':
            with open(path) as f:
                text = f.read()
            try:
                code = assemble(text)
            except AsmError as e:
                raise SystemExit(f'{file}: {e}')
        elif ext == '.ch8':
            with open(path, 'rb') as f:
                code = f.read()
            text = ''
            info = os.path.join(ROM_DIR, base + '.txt')
            if os.path.exists(info):
                with open(info) as f:
                    text = f.read()
        else:
            continue
        if len(code) > MAX_SIZE:
            raise SystemExit(f'{file}: {len(code)} bytes, the limit is {MAX_SIZE}')
        meta = metadata(text, base.upper())
        name = meta['name'].upper()[:16]
        if not set(name) <= NAME_CHARS:
            raise SystemExit(f'{file}: the font has no glyph for some letter of "{name}"')
        quirks = {'vip': 'QUIRKS_VIP', 'chip48': 'QUIRKS_CHIP48',
                  'schip': 'QUIRKS_SCHIP'}.get(meta['quirks'].lower())
        if not quirks:
            raise SystemExit(f'{file}: quirks must be vip, chip48 or schip')
        entries.append((base, name, code, c_keys(meta['keys'], file), quirks,
                        int(meta['speed'])))

    if not entries:
        raise SystemExit('no ROMs found in chip8/roms')
    entries.sort(key=lambda e: e[1])            # menu in alphabetical order

    lines = [
        '/**',
        '    ROM table of the CHIP-8 interpreter.',
        '    Generated by chip8/make_roms.py from chip8/roms/ - do not edit.',
        '*/',
        '',
    ]
    for base, name, code, keys, quirks, speed in entries:
        ident = 'rom_' + re.sub(r'\W', '_', base.lower())
        lines.append(f'static const uint8_t {ident}[{len(code)}] = {{')
        for i in range(0, len(code), 12):
            lines.append('    ' + ', '.join(f'0x{b:02X}' for b in code[i:i + 12]) + ',')
        lines.append('};')
        lines.append('')
    lines.append('static const struct rom_info roms[] = {')
    for base, name, code, keys, quirks, speed in entries:
        ident = 'rom_' + re.sub(r'\W', '_', base.lower())
        lines.append(f'    {{"{name}", {ident}, sizeof({ident}),')
        lines.append(f'        {{{keys}}}, {quirks}, {speed}}},')
    lines.append('};')
    lines.append('#define ROM_COUNT (sizeof(roms) / sizeof(roms[0]))')
    lines.append('')

    with open(OUTPUT, 'w') as f:
        f.write('\n'.join(lines))
    for base, name, code, keys, quirks, speed in entries:
        print(f'{name:16} {len(code):5} bytes  keys {{{keys}}}  {quirks} speed {speed}')
    print(f'-> {os.path.relpath(OUTPUT)}')


if __name__ == '__main__':
    sys.path.insert(0, HERE)
    main()
